# 50 km/h * 1.2 = 60 km/h, the fastest action in the SRC action set.
SPEED_FACTOR = 1.2
# Vissim numbers connectors from 10000 up in this file; they become SUMO's internal
# edges and never appear as named ones.
CONNECTOR_ID_BASE = 10000


def drop_build_time(net: Path) -> None:
    """Remove netconvert's build timestamp from the net it just wrote.

    The network is committed, so that a diff answers "did the scenario change?". A
    timestamp in the header makes every rebuild a diff and the question unanswerable.
    Everything else netconvert writes is deterministic, including the version and the
    full configuration it was invoked with, and those are the provenance worth keeping.
    """
    lines = net.read_text().splitlines(keepends=True)
    for index, line in enumerate(lines):
        if line.startswith("<!-- generated on "):
            _, _, tail = line.partition(" by ")
            lines[index] = f"<!-- generated by {tail}"
            break
    net.write_text("".join(lines))


def add_exit_constraint(net: Path, speed_mps: float, green_fraction: float,
                        cycle_s: float, lanes: int = 0) -> float:
    """Continue the network past its exit into a road whose discharge we set.

    Vehicles reaching the end of a route leave instantly, so whatever edge they leave
    from sets the outflow cap. Here that is link 218, three lanes at 60 km/h, which
    caps outflow at 3,899 veh/h -- above the 2,880 the network delivers, so it never
    binds and the exit behaves as a sink that absorbs everything offered. A road does
    not do that: it continues into another road that can carry a finite flow.

    The SRC paper describes a backpressure element at the exit, but no published
    layout contains one -- the conflict area on link 218 is PASSIVE in the base and
    absent from all four signalised variants -- so this is a stated modelling choice of
    ours rather than a reproduction of theirs.

    THE CONSTRAINT IS THE SIGNAL, NOT THE JUNCTION. Two earlier versions cut network
    discharge from 2,880 to about 1,000 veh/h whatever rate was configured, because the
    junction they created was itself the bottleneck, in two ways that the produced net
    shows directly. The connections fanned each of 218's three lanes into each of the
    exit road's, so the nine movements crossed and yielded to one another: junction
    218-end carried nine internal lanes and a foe matrix in which movement 2 conflicts
    with six others. And the exit road ran due east while 218 arrives heading 40 degrees
    north of east, so netconvert read every connection as a turn and capped the internal
    lanes at 7.6 to 11.9 m/s against 16.67 m/s on both sides.

    The exit road therefore takes 218's own lane count and its own heading, and lane i
    connects only to lane i. That leaves no crossing movements and no turn, so the only
    thing restricting outflow is the signal, and the rate is a number we choose.

    Returns the discharge the meter allows, in veh/h.
    """
    import sumolib

    loaded = sumolib.net.readNet(str(net))
    link = loaded.getEdge("218")
    source_lanes = link.getLaneNumber()
    lanes = lanes or source_lanes
    end = link.getToNode()
    x, y = end.getCoord()
    # Extend along the link's own final heading. Placing the nodes on a compass
    # direction instead is what made netconvert treat the exit as a turn.
    (px, py), (qx, qy) = link.getShape()[-2:]
    span = math.hypot(qx - px, qy - py)
    ux, uy = (qx - px) / span, (qy - py) / span

    directory = net.parent
    signalled = green_fraction > 0.0
    (directory / "exit.nod.xml").write_text(
        f'<nodes><node id="exit_meter" x="{x + 300.0 * ux:.2f}" '
        f'y="{y + 300.0 * uy:.2f}"'
        f'{" type=\"traffic_light\"" if signalled else ""}/>'
        f'<node id="exit_sink" x="{x + 600.0 * ux:.2f}" '
        f'y="{y + 600.0 * uy:.2f}"/></nodes>')
    (directory / "exit.edg.xml").write_text(
        f'<edges><edge id="exit_road" from="{end.getID()}" to="exit_meter" '
        f'numLanes="{lanes}" speed="{speed_mps:.3f}"/>'
        f'<edge id="exit_tail" from="exit_meter" to="exit_sink" '
        f'numLanes="{lanes}" speed="{speed_mps:.3f}"/></edges>')
    # Merging an edge into an existing SUMO net does not generate the connections into
    # it, so a route through the new edge breaks unless they are given explicitly.
    # Lane i runs straight into lane i where the widths match. Where the exit road is
    # NARROWER the surplus lanes merge into the outermost one, which is a lane drop and
    # a real merge: that turbulence is where a capacity drop comes from, and link 218
    # ending into free outflow has none. Earlier versions fanned every lane into every
    # lane, which made the movements cross and throttled the junction itself.
    connections = "".join(
        f'<connection from="218" to="exit_road" fromLane="{i}" '
        f'toLane="{min(i, lanes - 1)}"/>' for i in range(source_lanes)
    ) + "".join(
        f'<connection from="exit_road" to="exit_tail" fromLane="{i}" toLane="{i}"/>'
        for i in range(lanes))
    (directory / "exit.con.xml").write_text(f"<connections>{connections}</connections>")
    # The meter's program, written out rather than derived, so the green share is the
    # number chosen and not whatever netconvert infers.
    yellow = 3.0
    green = max(5.0, round(green_fraction * cycle_s - yellow)) if signalled else cycle_s
    red = max(5.0, cycle_s - green - yellow) if signalled else 0.0
    (directory / "exit.tll.xml").write_text(
        "<tlLogics></tlLogics>" if not signalled else
        f'<tlLogics><tlLogic id="exit_meter" type="static" programID="0" offset="0">'
        f'<phase duration="{green:.0f}" state="{"G" * lanes}"/>'
        f'<phase duration="{yellow:.0f}" state="{"y" * lanes}"/>'
        f'<phase duration="{red:.0f}" state="{"r" * lanes}"/>'
        f'</tlLogic></tlLogics>')
    binary = REPO_ROOT / ".venv" / "bin" / "netconvert"
    result = subprocess.run(
        [str(binary if binary.exists() else "netconvert"),
         "--sumo-net-file", str(net),
         "--node-files", str(directory / "exit.nod.xml"),
         "--edge-files", str(directory / "exit.edg.xml"),
         "--connection-files", str(directory / "exit.con.xml"),
         "--tllogic-files", str(directory / "exit.tll.xml"),
         "-o", str(net)],
        capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        raise SystemExit("netconvert failed adding the exit constraint")
    drop_build_time(net)
    # An upper bound only: the W99 following distance at free-flow speed, times the
    # green share. Real discharge is well under it, because a queue restarting from
    # rest does not reach free-flow headways within a green. At 0.85 green the bound is
    # 3,206 veh/h and `measure_fd_exit.py` reads about 1,900.
    per_lane = speed_mps / (speed_mps * 2.5 + 4.5) * 3600
    return per_lane * lanes * (green / cycle_s)


def run_netconvert(inpx: Path, out: Path) -> None:
    binary = REPO_ROOT / ".venv" / "bin" / "netconvert"
    command = [
        str(binary if binary.exists() else "netconvert"),
        "--vissim-file", str(inpx),
        # Without this the imported z-offsets produce edge grades up to 923%, which
        # SUMO applies to acceleration.
        "--flatten",
        "--speed.factor", str(SPEED_FACTOR),
        "-o", str(out),
    ]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        raise SystemExit(f"netconvert failed with code {result.returncode}")
    refused = re.findall(r"Will not build edge '(\d+)'", result.stderr)
    if refused:
        print(f"  netconvert refused {len(refused)} edges: {sorted(refused, key=int)}")


def edge_ids(net_file: Path) -> set[str]:
    root = ET.parse(net_file).getroot()
    return {
        edge.get("id")
        for edge in root.findall("edge")
        if edge.get("function") != "internal"
    }


def expand(link_no: str, present: set[str]) -> list[str]:
    """A Vissim link id as the SUMO edges it became, in order.

    Returns the empty list for a link netconvert did not build, so a caller that
    drops it does so knowingly rather than by producing a route with a hole in it.
    """
    if link_no in present:
        return [link_no]
    parts = sorted(
        (e for e in present if re.fullmatch(rf"{re.escape(link_no)}\[\d+\]", e)),
        key=lambda e: int(e.split("[")[1].rstrip("]")),
    )
    return parts


def outgoing(net_file: Path) -> dict[str, set[str]]:
    """Edge to the edges reachable from it in one step, via connections."""
    root = ET.parse(net_file).getroot()
    links: dict[str, set[str]] = {}
    for connection in root.findall("connection"):
        source, target = connection.get("from"), connection.get("to")
        if source and target and not source.startswith(":"):
            links.setdefault(source, set()).add(target)
    return links


def demand(inpx_root: ET.Element) -> dict[str, list[tuple[float, float, float]]]:
    """Entry link to its `(start_s, end_s, veh/h)` intervals.

    The demand is NOT constant and reading only its first interval more than doubles
    it: every entry runs at its stated volume for the first 1,200 s and at zero
    afterwards, so the episode is a twenty-minute surge followed by a drain. Holding
    the opening volume for the whole 2,500 s offers 12,500 vehicles where the scenario
    offers 6,000.
    """
    schedule: dict[str, list[tuple[float, float, float]]] = {}
    for vehicle_input in inpx_root.find("vehicleInputs").findall("vehicleInput"):
        points = sorted(
            (float(entry.get("timeInt").split()[1]) / 1000.0, float(entry.get("volume")))
            for entry in vehicle_input.find("timeIntVehVols").findall("timeIntervalVehVolume")
        )
        if not any(volume > 0.0 for _, volume in points):
            continue
        intervals = []
        for index, (start, volume) in enumerate(points):
            end = points[index + 1][0] if index + 1 < len(points) else float("inf")
            if volume > 0.0:
                intervals.append((start, end, volume))
        schedule[vehicle_input.get("link")] = intervals
    return schedule


def routes(inpx_root: ET.Element, present: set[str], entries: set[str],
           exit_road: bool = False) -> dict[str, list[str]]:
    """Entry link to its route as SUMO edges.

    Every route in this network ends at link 218, so one route per entry describes the
    demand completely and no route choice has to be modelled.
    """
    built: dict[str, list[str]] = {}
    decisions = inpx_root.find("vehicleRoutingDecisionsStatic")
    for decision in decisions.findall("vehicleRoutingDecisionStatic"):
        entry = decision.get("link")
        if entry not in entries or entry in built:
            continue
        static = decision.find("vehRoutSta")
        if static is None:
            continue
        for route in static.findall("vehicleRouteStatic"):
            # THE ROUTE STARTS AT THE ENTRY LINK. A Vissim routing decision sits ON a
            # link at some position along it and its `linkSeq` is the path onward from
            # there, so the sequence alone omits the link the vehicles are generated
            # on. Dropping it inserted traffic directly onto the next edge, which for
            # three of the eight entries is a single lane where the entry link has two
            # or three, throttling insertion and leaving thousands of vehicles queued
            # outside a network that never filled.
            # THE ROUTE ALSO ENDS AT THE DESTINATION LINK. `linkSeq` is the path
            # BETWEEN the decision point and the destination and names neither, so a
            # route built from it alone omits both ends. The destination here is link
            # 218, three lanes where the link feeding it has four -- a lane drop at the
            # exit. Skipping it removed the network's own outflow constraint and let
            # vehicles leave from a four-lane edge into nothing.
            sequence = [entry] + [
                ref.get("key") for ref in route.find("linkSeq").findall("intObjectRef")
            ] + [route.get("destLink")] + (["exit_road", "exit_tail"] if exit_road else [])
            path = [edge for key in sequence for edge in expand(key, present)]
            if path:
                built[entry] = path
                break
    return built


def check_connected(path: list[str], links: dict[str, set[str]]) -> list[tuple[str, str]]:
    return [
        (path[i], path[i + 1])
        for i in range(len(path) - 1)
        if path[i + 1] not in links.get(path[i], set())
    ]


def rush(volumes: dict[str, list[tuple[float, float, float]]],
         duration_s: float) -> dict[str, list[tuple[float, float, float]]]:
    """Reshape every entry's demand into a rush that rises to a peak and falls back.

    A constant rate puts the network at one point on its flow-density curve and leaves
    it there, so tracing the curve needs one run per point. A rush traces it in a single
    run: demand climbs from a quarter of the peak to the peak and back down, and a
    detector on the road passes through free flow, capacity and congestion as the queue
    from the downstream restriction grows over it and then clears.

    Both halves are kept so they can be compared. If the loading and unloading legs do
    not lie on the same branches, what is being measured is a transient rather than a
    property of the road.

    The opening volume of each entry is its peak, so `--demand-scale` sets the height of
    the rush and the mix across the eight entries is the scenario's own.
    """
    steps = 12
    half = duration_s / 2.0
    shape = [(half * index / (steps - 1), 0.25 + 0.75 * index / (steps - 1))
             for index in range(steps)]
    shape += [(half + half * index / (steps - 1), 1.0 - 0.75 * index / (steps - 1))
              for index in range(1, steps)]
    reshaped = {}
    for entry, intervals in volumes.items():
        peak = intervals[0][2]
        reshaped[entry] = [
            (start,
             shape[index + 1][0] if index + 1 < len(shape) else duration_s,
             peak * share)
            for index, (start, share) in enumerate(shape)
        ]
    return reshaped


def burst(volumes: dict[str, list[tuple[float, float, float]]], start: float, end: float,
          scale: float, opening: dict[str, float] | None = None,
          ) -> dict[str, list[tuple[float, float, float]]]:
    """Replace every entry's rate on `[start, end)` by its opening volume times `scale`.

    The opening volume is the entry's first `.inpx` volume before `--demand-scale`, so
    `--demand-scale S --demand-burst a b B` gives each entry the opening volume times S
    outside `[a, b)` and times B inside it. `opening` carries those unscaled volumes;
    without it each entry's first interval in `volumes` is taken as its opening volume.
    The intervals outside the burst keep their own rates and are clipped at its edges.
    """
    shaped: dict[str, list[tuple[float, float, float]]] = {}
    for entry, intervals in volumes.items():
        peak = opening[entry] if opening is not None else intervals[0][2]
        pieces = []
        for low, high, rate in intervals:
            if low < min(high, start):
                pieces.append((low, min(high, start), rate))
            if max(low, end) < high:
                pieces.append((max(low, end), high, rate))
        pieces.append((start, end, peak * scale))
        shaped[entry] = sorted(pieces)
    return shaped


def vtype_lines(model: str = "eidm_reaction",
                junction_block_s: float | None = None) -> list[str]:
    """Vehicle types from a named human-model config.

    Every key under the config's `sumo` block other than the model name and the
    standstill gap is written straight through as a vType attribute, so a config can
    carry W99's cc1..cc9 or EIDM's tau and actionStepLength without this function
    knowing which.

    The default is `eidm_reaction` rather than the paper's `w99_calibrated`. Under W99
    a bottleneck's discharge does not fall once a queue stands behind it -- it rises --
    so served flow is a constant and there is no capacity drop for a density-holding
    controller to recover. That config's header carries the measurements.
    """
    import yaml

    config = yaml.safe_load(
        (REPO_ROOT / "configs" / "human_models" / f"{model}.yaml").read_text())
    sumo = config["sumo"]
    attributes = " ".join(
        f'{name}="{value}"' for name, value in sumo.items()
        if name not in ("car_following_model", "min_gap_m")
    )
    common = (f'carFollowModel="{sumo["car_following_model"]}" '
              f'minGap="{sumo["min_gap_m"]}" {attributes} maxSpeed="16.67"')
    if junction_block_s is not None:
        # JUNCTION BLOCKING, AND IT IS A MODELLING CHOICE OF OURS, not the paper's.
        # SUMO keeps a vehicle out of a junction it cannot clear, which prevents
        # deadlock and also prevents the throughput loss that blocking causes in a
        # real network: measured with no control, Mainz served a constant 2,853 to
        # 2,894 veh/h while interior links reached 125 veh/km/lane at 0.8 km/h, so
        # gridlock cost it nothing. `jmIgnoreKeepClearTime` is the accumulated waiting
        # time after which a vehicle enters anyway; SUMO's default of -1 means never.
        # Vissim's conflict areas model the same behaviour, which is the ground for
        # choosing it, but the value here is ours and is not transcribed from anything.
        common += f' jmIgnoreKeepClearTime="{junction_block_s:g}"'
    return [
        f'  <vType id="human" {common}/>',
        f'  <vType id="av" {common} color="1,0,0"/>',
    ]


def write_routes(out_path: Path, built: dict[str, list[str]], volumes: dict[str, float],
                 duration_s: float, av_fraction: float, seed: int,
                 junction_block_s: float | None = None,
                 human_model: str = "eidm_reaction", name: str = "mainz") -> int:
    """One explicit departure per vehicle, evenly spaced, sorted by time.

    Explicit vehicles rather than `<flow>` so a vehicle's id encodes whether it is an
    AV: SRC selects its controlled subset by vehicle number, and reproducing that here
    keeps the penetration deterministic and inspectable instead of resting on a draw.

    Three files are written from the one schedule, so the two admission policies are
    the same demand rather than two demands that happen to match:

    * `mainz.rou.xml`, routes and every vehicle, which SUMO inserts on its own terms.
    * `mainz_routes.rou.xml`, the same routes and vehicle types with no vehicles, for
      runs where `MainzEnv` grants entry itself.
    * `mainz_schedule.json`, the vehicles that file omits, with the entry link each one
      is waiting at so the gate can be applied per entry.

    `name` replaces the `mainz` stem of the two files written beside `out_path`.
    """
    header = ["<routes>"] + vtype_lines(human_model, junction_block_s)
    for entry, edges in sorted(built.items(), key=lambda kv: int(kv[0])):
        header.append(f'  <route id="r{entry}" edges="{" ".join(edges)}"/>')
    departures: list[tuple[float, str, str]] = []
    for entry, intervals in sorted(volumes.items(), key=lambda kv: int(kv[0])):
        if entry not in built:
            continue
        for start, end, rate in intervals:
            headway = 3600.0 / rate
            time = start + headway / 2.0
            limit = min(end, duration_s)
            while time < limit:
                departures.append((time, entry, f"v{entry}_{len(departures)}"))
                time += headway
    departures.sort()
    schedule = []
    lines = list(header)
    for index, (time, entry, vehicle_id) in enumerate(departures):
        kind = "av" if (index % round(1.0 / av_fraction) == 0) else "human"
        lines.append(
            f'  <vehicle id="{vehicle_id}" type="{kind}" route="r{entry}" '
            f'depart="{time:.2f}" departSpeed="max" departLane="best"/>'
        )
        schedule.append({"id": vehicle_id, "route": f"r{entry}", "type": kind,
                         "depart": round(time, 2), "entry": entry})
    lines.append("</routes>")
    out_path.write_text("\n".join(lines) + "\n")
    out_path.with_name(f"{name}_routes.rou.xml").write_text(
        "\n".join(header + ["</routes>"]) + "\n")
    out_path.with_name(f"{name}_schedule.json").write_text(json.dumps(schedule))
    return len(departures)


def _file_sha256(path: Path) -> str:
    import hashlib

    return hashlib.sha256(path.read_bytes()).hexdigest()


